/**
 * Client-half bundler.
 *
 * `lib/client.js` is not an ES module. The web shell installs a registration sink
 * on `window.__ModuleLoader__` and executes each bundle as a classic script, so a
 * bundle's **only** top-level statement is that registration call:
 *
 * ```js
 * window.__ModuleLoader__.load({
 *   id: '<package name>',
 *   factory: (require) => { ...whole bundle...; return exports },
 * })
 * ```
 *
 * Contract source: `@deepseek-ai/dsh-client-modules@0.0.1-rc.1`
 * (`ClientPluginHandoff`, `DshWindow.__ModuleLoader__`). Executing the script only
 * registers the factory; every side effect — including CSS injection — waits for
 * materialization on first import. This is exactly why the spec forbids a
 * lazily-bundled ESM output and why the bundle must not touch the DOM at load.
 *
 * The factory receives a synchronous `require` bound to the module table, which
 * is how platform singletons (`react`, `@deepseek-ai/cordis`, the slots package)
 * arrive. They are marked external so they are never duplicated into our bundle —
 * a second React copy would break hooks and the slot renderer alike.
 *
 * @module dsh-latex-preview/scripts/build-client
 */

import { build } from 'esbuild'
import { readFile, rm } from 'node:fs/promises'

const OUT = 'lib/client.js'
const pkg = JSON.parse(await readFile('package.json', 'utf8'))
const id = pkg.name

await rm(OUT, { force: true })

await build({
  entryPoints: ['src/client/index.ts'],
  outfile: OUT,
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  sourcemap: true,
  legalComments: 'none',
  external: [
    'react',
    'react-dom',
    'react/jsx-runtime',
    '@deepseek-ai/cordis',
    '@deepseek-ai/dsh-client-ui-slots',
    '@deepseek-ai/dsh-client-runtime',
    '@deepseek-ai/dsh-client-web-react',
    '@deepseek-ai/dsh-client-ui-primitives',
    '@deepseek-ai/dsh-typert-protocol',
    '@deepseek-ai/dsh-llm',
  ],
  banner: {
    js: [
      `/* Generated by scripts/build-client.mjs — do not edit. */`,
      `window.__ModuleLoader__.load({`,
      `  id: ${JSON.stringify(id)},`,
      `  factory: function (require) {`,
      `    var module = { exports: {} };`,
      `    var exports = module.exports;`,
    ].join('\n'),
  },
  footer: {
    js: [`    return module.exports;`, `  },`, `});`].join('\n'),
  },
})

console.log(`built ${OUT} (module-loader registration for "${id}")`)
