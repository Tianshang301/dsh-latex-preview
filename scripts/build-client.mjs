/**
 * Client-half bundler.
 *
 * `lib/client.js` is a browser artifact, not an ES module: the shell loads it
 * into its frozen module table, so a top-level `import`/`export` would break.
 *
 * We emit a single top-level statement — one IIFE assigned to a global name —
 * so every side effect stays inside the factory and nothing fires merely by
 * loading the file. The shell reads the resulting object and calls its `apply`.
 *
 * OPEN (docs/spikes.md B7): the exact loader handshake the shell expects. The
 * only published third-party plugin in this ecosystem shipped no client bundle,
 * so there is no reference implementation to copy yet. The IIFE-with-global-name
 * form is the conservative choice: it can be turned into whatever the loader
 * wants with a one-line wrapper, and it already satisfies the "single top-level
 * statement, side effects inside the factory" rule.
 *
 * @module dsh-latex-preview/scripts/build-client
 */

import { build } from 'esbuild'
import { rm } from 'node:fs/promises'

const OUT = 'lib/client.js'

await rm(OUT, { force: true })

await build({
  entryPoints: ['src/client/index.ts'],
  outfile: OUT,
  bundle: true,
  format: 'iife',
  globalName: '__dshLatexPreviewClient',
  platform: 'browser',
  target: ['es2022'],
  sourcemap: true,
  legalComments: 'none',
  // Provided by the shell at runtime; never bundled.
  external: ['@deepseek-ai/*', 'react', 'react-dom', 'react/jsx-runtime'],
  banner: {
    js: ['/* Generated by scripts/build-client.mjs — do not edit. */'].join('\n'),
  },
})

console.log(`built ${OUT} (IIFE, single top-level statement)`)
